"""Write docs/CODEMAP.md: one line per source file, so a new worker can skip most of the exploring.

    python tools/codemap.py
"""
import ast
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
HEADER = """# SnapLab code map

Generated by `python tools/codemap.py`. How the parts fit together is in [MAP.md](MAP.md), past changes in
[CHANGELOG.md](CHANGELOG.md). Use this list to find the file you need, then read only the part you need.

## Common starting points

- UI text: `web/i18n/en.js`, `ja.js`, `ru.js`
- UI parts and behaviour: `web/app.js`; the look: `web/app.css`. Web files are read from disk on every request,
  so a change in `web/` needs no restart
- Icons: `web/icons/ui/<name>.svg` (line icons) and `web/icons/soft3d/` (3D icons)
- Bot tools: `snaplab/tools.py` (`CHAT_TOOLS` and `Toolbox`); their wording: `snaplab/prompts.py`
- SnapCode turns and results: `snaplab/sessions.py`; agent choice: `snaplab/harnesses/selection.py`; the
  workspace: `snaplab/harnesses/remote.py`
- Tools SnapCode can call: `snaplab/web_mcp.py`
- Tests: `python -m unittest discover -s tests`, UI checks: `node tests/<name>_ui.mjs`

## Files
"""


def python_line(path):
    tree = ast.parse(path.read_text(encoding='utf-8'))
    doc = (ast.get_docstring(tree) or '').strip().split('\n')[0]
    classes = [n.name for n in tree.body if isinstance(n, ast.ClassDef)]
    return doc + (' Classes: ' + ', '.join(classes[:6]) if classes else '')


def web_line(path):
    for line in path.read_text(encoding='utf-8', errors='ignore').splitlines()[:6]:
        match = re.match(r'\s*(?://|/\*+)\s*(.+?)\s*(?:\*/)?$', line)
        if match:
            return match.group(1)
    return ''


def main():
    lines = [HEADER]
    for folder, pattern, read in (('snaplab', '*.py', python_line), ('snaplab/harnesses', '*.py', python_line),
                                  ('snaplab/harnesses', '*.mjs', web_line), ('web', '*.js', web_line),
                                  ('tools', '*.py', python_line)):
        lines.append('\n### ' + folder + (' (Node)' if pattern == '*.mjs' else '') + '\n')
        for path in sorted((ROOT / folder).glob(pattern)):
            if path.name == '__init__.py' or (folder == 'tools' and re.match(r'(round\d|check_)', path.name)):
                continue
            count = len(path.read_text(encoding='utf-8', errors='ignore').splitlines())
            lines.append(f'- `{path.name}` ({count} lines): {read(path)}\n')
    out = ROOT / 'docs/CODEMAP.md'
    out.write_text(''.join(lines), encoding='utf-8', newline='\n')
    print(out, out.stat().st_size, 'bytes')


if __name__ == '__main__':
    main()
