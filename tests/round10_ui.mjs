import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
import { makeUI } from "./ui_harness.mjs";

for (const lang of ["en", "ja"]) {
  const { context, ui, document, requests } = makeUI();
  for (const file of ["en", "ja", "core"]) vm.runInContext(fs.readFileSync(new URL(`../web/i18n/${file}.js`, import.meta.url), "utf8"), context);
  ui.S.lang = lang;
  const root = document.createElement("div"); root.setAttribute("id", "app"); document.body.appendChild(root);
  ui.S.bots = [{ id: "b1", name: "Builder", initials: "B", projects: ["p1", "p2"] }, { id: "b2", name: "Reviewer", initials: "R" }];
  ui.S.projects = [{ id: "p1", name: "Calendar", bot: "b1" }, { id: "p2", name: "Notes", bot: "b1" }];
  ui.S.rooms = [{ id: "r1", kind: "group", name: "Planning", bots: ["b1", "b2"], bot_only: true }];
  const picker = ui.projectPicker(["p1", "p2"], "b1");
  const choices = picker.el.querySelectorAll('.pick-row');
  assert.equal(choices.length, 2);
  assert.ok(choices.every(x => x.getAttribute("aria-checked") === "true"));
  await choices[0].emit("click");
  assert.deepEqual(Array.from(picker.value()), ["p2"]);
  await choices[0].emit("click");
  assert.equal(picker.value().length, 2);
  const list = ui.chats();
  assert.equal(list.querySelectorAll(".bot-chat-label").length, 1);
  assert.match(list.textContent, lang === "ja" ? /Bot どうしが話しています/ : /Bots are talking here/);
  const message = ui.messageEl({ id: "m", room: "r1", bot: "b1", role: "bot", status: "done", text: "Hello", bot_conversation: true, to_bots: ["b2"] });
  assert.equal(message.querySelector(".msg-name").textContent, "Builder");
  assert.match(message.querySelector(".bot-chat-label").textContent, /Reviewer/);
  const link = ui.messageEl({ id: "note", role: "system", key: "note.bot_contact", vars: { name: "Planning" }, linked_room: "r1" });
  assert.equal(link.querySelector("a").getAttribute("href"), "#/room/r1");
  const q = { id: "q1", bot: "b1", room: "r1", kind: "approval", question: "Approval", status: "open", options: ["Approve", "Decline"], prop: { key: "prop.create_project", vars: { bot: "Builder" }, why: "web", fields: [] } };
  ui.onEvent({ type: "question.new", question: q });
  assert.equal(ui.needsCount(), 1);
  ui.needsSheet();
  const panel = ui.activeSheets.at(-1).panel;
  assert.match(panel.querySelector(".qcard-why").textContent, lang === "ja" ? /今回の返答中にウェブ/ : /during this reply/);
  assert.ok(!/\?{3}/.test(panel.textContent));
  ui.onEvent({ type: "question.updated", question: { ...q, status: "answered" } });
  assert.equal(ui.needsCount(), 0);
  const inherited = { ...q, id: "q2", prop: { ...q.prop, why: "web_conversation", why_vars: { reader: "Alpha" } } };
  ui.onEvent({ type: "question.new", question: inherited });
  ui.needsSheet();
  const reason = ui.activeSheets.at(-1).panel.querySelector(".qcard-why").textContent;
  assert.match(reason, /Alpha/);
  assert.match(reason, lang === "ja" ? /今回の返答にも引き継いでいます/ : /this reply inherits/);
  assert.ok(!reason.includes("{reader}"));
  ui.onEvent({ type: "question.updated", question: { ...inherited, status: "answered" } });
  const sessionRead = { ...q, id: "q3", prop: { ...q.prop, why: "web_session", why_vars: { session: "Source review" } } };
  ui.onEvent({ type: "question.new", question: sessionRead });
  ui.needsSheet();
  const sessionReason = ui.activeSheets.at(-1).panel.querySelector(".qcard-why").textContent;
  assert.match(sessionReason, lang === "ja" ? /作業（Source review）がウェブの資料を読みました/ : /Session \(Source review\) read web material/);
  assert.ok(!sessionReason.includes("{session}"));
}
console.log("Round 10 UI: multiple assignments, public bot conversations, destination links and approval inbox passed in English and Japanese.");
